"""BL-06 baseline: the shielded variant under each T2 disturbance profile.

Runs every shipped scenario, plus a no-wind symmetric crossing, for each T2
profile and seed, and writes the scenario x profile x seed table to
``docs/results/bl06-baseline-<date>.md``. The no-wind crossing is the hard case:
with wind on, the drones' arrival times drift apart and the exact symmetric
meeting the filter cannot resolve never happens.

These are measurements, not tests. Rows get promoted to tests once the C+D
filter adds a disturbance margin (TASKS.md BL-06).

Usage: python scripts/disturbance_matrix.py [--seeds 5] [--out docs/results]
"""

from __future__ import annotations

import argparse
import logging
import sys
from dataclasses import replace
from datetime import date
from pathlib import Path

from shared.contracts import SAFE_SEPARATION_M, ScenarioConfig

from utm_services.policy.reference import ReferencePolicy
from utm_services.simulation.env import PROFILES, DroneEnv
from utm_services.simulation.runner import run_episode

ROOT = Path(__file__).resolve().parents[1]
T2_PROFILES = ("nominal", "realistic")
# (case label, scenario file, wind on)
CASES = (
    ("head-on-40", "head-on-40", True),
    ("crossing-90", "crossing-90", True),
    ("crossing-90 no wind", "crossing-90", False),
    ("sandwich-3", "sandwich-3", True),
)


def run_matrix(seeds: int) -> list[dict]:
    rows = []
    for label, scenario, wind in CASES:
        cfg = ScenarioConfig.model_validate_json((ROOT / "scenarios" / f"{scenario}.json").read_text())
        for profile in T2_PROFILES:
            d = PROFILES[profile] if wind else replace(PROFILES[profile], wind_max_mps2=0.0)
            for seed in range(seeds):
                s = run_episode(cfg.model_copy(update={"seed": seed}), "shielded_marl", policy=ReferencePolicy(),
                                policy_id="reference-standin",
                                make_env=lambda rules, d=d: DroneEnv(rules, disturbances=d),
                                keep_records=False).summary
                rows.append({"case": label, "profile": profile, "seed": seed, **s})
    return rows


def to_markdown(rows: list[dict], today: str) -> str:
    lines = [
        f"# BL-06 baseline, {today}",
        "",
        "Shielded variant (`shielded_marl`, reference controller as stand-in), filter on the noisy, delayed",
        "states the server receives. Generated by `scripts/disturbance_matrix.py`. Both T2 profiles are",
        f"placeholders until real telemetry data exists. d_safe = {SAFE_SEPARATION_M:g} m.",
        "",
        "| Case | Profile | Seed | Min sep (m) | Keeps d_safe | Violation pair-steps | Fallbacks | Completed |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        keeps = "yes" if r["min_separation_m"] >= SAFE_SEPARATION_M else "no"
        lines.append(
            f"| {r['case']} | {r['profile']} | {r['seed']} | {r['min_separation_m']:.2f} | {keeps} "
            f"| {r['separation_violation_pair_steps']} | {r['fallback_events']} "
            f"| {r['n_completed']}/{r['n_launched']} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seeds", type=int, default=5, help="seeds 0..N-1 (default: 5)")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "results", help="output directory")
    args = parser.parse_args(argv)

    logging.disable(logging.WARNING)  # the filter logs every infeasible step
    try:
        rows = run_matrix(args.seeds)
    finally:
        logging.disable(logging.NOTSET)
    today = date.today().isoformat()
    table = to_markdown(rows, today)
    args.out.mkdir(parents=True, exist_ok=True)
    path = args.out / f"bl06-baseline-{today}.md"
    path.write_text(table, encoding="utf-8")
    print(table)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
